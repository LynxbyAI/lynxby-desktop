/// How much of a tool's result the thread shows; the audit ledger has the rest.
const RESULT_PREVIEW: usize = 600;

pub fn render(app: &mut LynxbyApp, window: &mut Window, cx: &mut Context<LynxbyApp>) -> Div {
    let Some(chat) = app.chat().cloned() else {
        return div();
    };

    let model = chat
        .assistant
        .model
        .clone()
        .unwrap_or_else(|| t("routed by Lynxby").to_string());
    let organisation = app
        .me()
        .map(|me| me.organisation_name())
        .unwrap_or_default();
    let focused = app.input().is_focused(window);
    let composer_empty = app.composer().is_empty();
    let composer_text = app.composer().text().to_string();
    let locked = chat.asking() && !chat.asking_text();

    let mut thread = div()
        .w_full()
        .max_w(px(760.))
        .mx_auto()
        .p_6()
        .flex()
        .flex_col()
        .gap_6();

    if let Some(run) = &chat.intake {
        thread = thread.children(intake_log(&chat, run, cx));
    }

    for (index, turn) in chat.turns.iter().enumerate() {
        let last = index + 1 == chat.turns.len();
        thread = thread.child(turn_view(&chat, index, turn, last && chat.streaming, cx));
    }

    thread = thread
        .children(
            chat.loading
                .then(|| widgets::info_box(t("Loading this conversation…")).into_any_element()),
        )
        .children(
            chat.error
                .clone()
                .map(|message| widgets::error_box(message).into_any_element()),
        )
        .children(chat.note.clone().map(|note| {
            div()
                .text_xs()
                .text_color(theme::text_muted())
                .child(note)
                .into_any_element()
        }))
        .child(
            div()
                .pt_2()
                .flex()
                .flex_col()
                .gap_1()
                .text_xs()
                .text_color(theme::text_subtle())
                .child(t("Answers are generated by an AI system, not written by a person. Check anything you rely on."))
                .child(format!(
                    "{}{}",
                    tf("Session {session}", &[("session", &chat.session_id)]),
                    t(" · usage is recorded on your organisation")
                )),
        );

    let hint = if chat.asking_text() {
        t("Answer in the box below · Enter to continue")
    } else {
        t("Enter to send · Shift+Enter for a new line")
    };

    div()
        .size_full()
        .flex()
        .flex_col()
        .child(header(&chat.assistant.name, &model, &organisation, cx))
        .child(
            div()
                .id("messages")
                .flex_1()
                .w_full()
                .overflow_y_scroll()
                .track_scroll(app.scroll())
                .child(thread),
        )
        .child(
            div()
                .w_full()
                .border_t_1()
                .border_color(theme::border())
                .bg(theme::surface_raised())
                .child(
                    div()
                        .w_full()
                        .max_w(px(760.))
                        .mx_auto()
                        .p_4()
                        .flex()
                        .flex_col()
                        .gap_2()
                        .child(
                            div()
                                .w_full()
                                .flex()
                                .items_end()
                                .gap_3()
                                .p_3()
                                .rounded_xl()
                                .border_1()
                                .border_color(if focused && !locked {
                                    theme::border_strong()
                                } else {
                                    theme::border()
                                })
                                .bg(theme::surface_sunken())
                                .when(locked, |composer| composer.opacity(0.5))
                                .id("composer")
                                .track_focus(app.input())
                                .on_key_down(cx.listener(
                                    |this, event: &KeyDownEvent, _window, cx| {
                                        this.on_key(event, cx)
                                    },
                                ))
                                .cursor_text()
                                .on_click(cx.listener(|this, _: &ClickEvent, window, _cx| {
                                    window.focus(this.input());
                                }))
                                .child(composer_row(
                                    focused && !locked,
                                    composer_empty,
                                    composer_text,
                                ))
                                .child(send_button(
                                    if chat.asking_text() {
                                        t("Continue")
                                    } else {
                                        t("Send")
                                    },
                                    chat.streaming || composer_empty || locked,
                                    cx,
                                )),
                        )
                        .child(div().text_xs().text_color(theme::text_subtle()).child(hint)),
                ),
        )
}

