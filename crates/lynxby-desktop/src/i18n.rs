//! The window's words in English and Dutch. English is the key, as in the web
//! app's `__()` and `$t()`; the language is the person's choice on the
//! deployment once signed in, and the system language before that.

use std::sync::atomic::{AtomicBool, Ordering};

static DUTCH: AtomicBool = AtomicBool::new(false);

/// `nl`, `nl_NL.UTF-8` and `nl-BE` all mean Dutch; anything else is English.
pub fn set(locale: &str) {
    DUTCH.store(
        locale.to_ascii_lowercase().starts_with("nl"),
        Ordering::Relaxed,
    );
}

/// shortcut: reads the POSIX locale variables only; Windows and macOS start in
/// English until the deployment names the person's language at sign-in.
pub fn set_from_system() {
    for name in ["LC_ALL", "LC_MESSAGES", "LANG"] {
        if let Ok(value) = std::env::var(name) {
            if !value.is_empty() {
                set(&value);
                return;
            }
        }
    }
}

pub fn is_dutch() -> bool {
    DUTCH.load(Ordering::Relaxed)
}

pub fn t(english: &'static str) -> &'static str {
    if is_dutch() {
        dutch(english).unwrap_or(english)
    } else {
        english
    }
}

/// `t()` with `{name}` placeholders filled in.
pub fn tf(english: &'static str, values: &[(&str, &str)]) -> String {
    values
        .iter()
        .fold(t(english).to_string(), |text, (name, value)| {
            text.replace(&format!("{{{name}}}"), value)
        })
}

/// A string that arrives at run time, such as a fallback label from the
/// client crate, in the person's language when there is a translation.
pub fn translate(text: &str) -> String {
    match dutch(text) {
        Some(dutch) if is_dutch() => dutch.to_string(),
        _ => text.to_string(),
    }
}

