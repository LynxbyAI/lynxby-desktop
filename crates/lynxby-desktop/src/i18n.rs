#[cfg(test)]
mod tests {
    use super::*;

    /// Every literal passed to `t()` or `tf()` in the window's source.
    fn keys() -> Vec<String> {
        let sources = [
            include_str!("app.rs"),
            include_str!("widgets.rs"),
            include_str!("screens/assistants.rs"),
            include_str!("screens/chat.rs"),
            include_str!("screens/login.rs"),
        ];
        let mut keys = Vec::new();

        for source in sources {
            for pattern in ["t(\"", "tf(\""] {
                for (start, _) in source.match_indices(pattern) {
                    let before = source[..start].chars().last();
                    if before.is_some_and(|c| c.is_alphanumeric() || c == '_') {
                        continue;
                    }
                    let rest = &source[start + pattern.len()..];
                    let end = rest.find('"').expect("a closed literal");
                    keys.push(rest[..end].to_string());
                }
            }
        }

        keys
    }

    #[test]
    fn every_string_on_screen_has_a_dutch_translation() {
        let keys = keys();
        assert!(
            keys.len() > 30,
            "the scan found only {} strings",
            keys.len()
        );

        let missing: Vec<_> = keys.iter().filter(|key| dutch(key).is_none()).collect();
        assert!(missing.is_empty(), "no Dutch for: {missing:#?}");
    }

    #[test]
    fn placeholders_are_filled_in_either_language() {
        set("nl_NL.UTF-8");
        assert_eq!(
            tf(
                "Question {current} of {total}",
                &[("current", "2"), ("total", "5")]
            ),
            "Vraag 2 van 5"
        );
        set("en");
        assert_eq!(
            tf(
                "Question {current} of {total}",
                &[("current", "2"), ("total", "5")]
            ),
            "Question 2 of 5"
        );
    }
}
